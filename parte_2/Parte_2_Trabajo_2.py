def calcular_lgd_objetivo(df_entrada):
    """
    Calcula la LGD objetivo a partir de los campos financieros del dataset.
    Aplica acotamiento al rango [0, 1].
    """
    df_lgd = df_entrada.copy()

    # Extraer campos de la fórmula
    monto_financiado = pd.to_numeric(df_lgd["funded_amnt"], errors="coerce")
    rec_principal = pd.to_numeric(df_lgd["total_rec_prncp"], errors="coerce").fillna(0)
    rec_bruta = pd.to_numeric(df_lgd["recoveries"], errors="coerce").fillna(0)
    costo_cobranza = pd.to_numeric(df_lgd["collection_recovery_fee"], errors="coerce").fillna(0)

    # Recuperaciones netas de costos de cobranza
    recuperacion_neta = rec_principal + rec_bruta - costo_cobranza

    # LGD = 1 - (Recuperación Neta / Exposición)
    lgd_bruta = 1.0 - (recuperacion_neta / monto_financiado)

    # Acotar al intervalo [0, 1]
    return np.clip(lgd_bruta, 0.0, 1.0)

