"""### 3. Red neuronal para estimar la LGD (MLP Regresor)

#### Justificación de la función de pérdida y la activación de salida
1. **Naturaleza de la variable objetivo ($\text{LGD}$):** La LGD es una variable continua que representa una fracción acotada en el intervalo $[0, 1]$.
2. **Función de Pérdida (MSE / Error Cuadrático Medio):** Para la estimación de la LGD mediante un perceptrón multicapa, se utiliza el Error Cuadrático Medio ($\text{MSE}$):
   $$\text{MSE} = \frac{1}{n} \sum_{i=1}^{n} (y_i - \hat{y}_i)^2$$
   **Derivación probabilística (Máxima Verosimilitud):** Asumiendo que el error del modelo $y_i - \hat{y}_i$ sigue una distribución normal condicional con media cero y varianza constante, $Y_i \mid x_i \sim \mathcal{N}(\hat{y}_i, \sigma^2)$, la función de log-verosimilitud es:
   $$\ln L(w) = -\frac{n}{2}\ln(2\pi\sigma^2) - \frac{1}{2\sigma^2} \sum_{i=1}^{n} (y_i - \hat{y}_i(w))^2$$
   Maximizar la verosimilitud respecto a los pesos $w$ del perceptrón equivale exactamente a minimizar la suma de errores al cuadrado ($\text{MSE}$).
3. **Activación de la capa de salida y acotamiento:** La implementación estándar de `MLPRegressor` en `scikit-learn` utiliza la función de activación identidad en la capa de salida ($\hat{y} = z$). Para garantizar que las estimaciones sean totalmente coherentes con el dominio de una fracción de pérdida, las predicciones del modelo se proyectan/acotan determinísticamente al rango $[0, 1]$ mediante la función $\hat{y}_{\text{acotada}} = \min(\max(\hat{y}, 0), 1)$.

#### Regla de comparación justa y protocolo de búsqueda
Se evalúa un presupuesto explícito de configuraciones explorando combinaciones de arquitecturas de capas ocultas, funciones de activación (`relu` y `tanh`), intensidades de regularización $L_2$ (`alpha`) y tasas de aprendizaje iniciales (`learning_rate_init`). El modelo final seleccionado se somete al experimento de variabilidad entrenando con **30 semillas aleatorias independientes** (de la 42 a la 71).
"""

