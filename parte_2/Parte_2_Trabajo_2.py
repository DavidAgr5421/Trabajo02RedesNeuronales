"""### 5 y 6. Pérdida Esperada ($E[L]$) y Exposición al Incumplimiento ($\text{EAD}$)

#### Definición y justificación de la $\text{EAD}$
La Exposición al Incumplimiento ($\text{EAD}$, por sus siglas en inglés) se define como el monto total adeudado o expuesto en el momento exacto en que el cliente entra en mora.

En este trabajo se utiliza el campo **`funded_amnt`** (Monto financiado) como medida de $\text{EAD}$. Esta decisión se justifica porque:
1. Representa el valor contractual total desembolsado por la plataforma al cliente al inicio del crédito.
2. Como se demostró en la auditoría del código, el saldo pendiente `out_prncp` toma el valor $0$ en los préstamos castigados, por lo que no refleja el balance real al momento del impago.

#### Formulación de la Pérdida Esperada
Para cada crédito $i$, la Pérdida Esperada se calcula combinando las salidas del modelo de clasificación ($\text{PD}$) y del modelo de regresión ($\text{LGD}$) junto con la $\text{EAD}$:
$$E[L]_i = \text{PD}_i \times \text{LGD}_i \times \text{EAD}_i$$
"""

