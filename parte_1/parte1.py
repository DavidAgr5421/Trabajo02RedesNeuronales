# 23.1. Entrenamiento con validación temporal externa
def fit_mlp_external_validation(prepared, params, seed, config):

    start = time.perf_counter()

    model = MLPClassifier(
        hidden_layer_sizes=tuple(params["hidden_layer_sizes"]),
        activation=params["activation"],
        solver=params["solver"],
        alpha=params["alpha"],
        learning_rate="constant",
        learning_rate_init=params["learning_rate_init"],
        batch_size=config["batch_size"],
        shuffle=True,
        random_state=seed,
        early_stopping=False,
        momentum=0.9,
        nesterovs_momentum=False,
        beta_1=0.9,
        beta_2=0.999,
        epsilon=1e-8
    )

    best_model = None
    best_loss = np.inf
    reference_loss = np.inf
    stale = 0
    best_epoch = 0
    history = []
    stop_reason = "max_epocas"

    for epoch in range(1, config["max_epocas"] + 1):

        # Avanzar una época conservando el optimizador
        model.partial_fit(
            prepared["X_train"],
            prepared["y_train"],
            classes=np.array([0, 1])
        )

        # Evaluación sobre validation
        p_val = model.predict_proba(
            prepared["X_val"]
        )[:, 1]

        loss_val = log_loss(
            prepared["y_val"],
            p_val,
            labels=[0, 1]
        )

        if not np.isfinite(loss_val) or not np.isfinite(model.loss_):
            raise FloatingPointError(
                "Entrenamiento no finito. Revisar escala y parámetros."
            )

        history.append({
            "epoch": epoch,
            "train_loss_regularized": float(model.loss_),
            "validation_BCE": float(loss_val)
        })

        # Guardar el checkpoint con menor BCE
        if loss_val < best_loss:
            best_loss = float(loss_val)
            best_model = deepcopy(model)
            best_epoch = epoch

        # Control de paciencia
        if loss_val < reference_loss - config["min_delta"]:
            reference_loss = float(loss_val)
            stale = 0
        else:
            stale += 1

        if stale >= config["paciencia"]:
            stop_reason = "paciencia_validation"
            break

    if best_model is None:
        raise RuntimeError("No se obtuvo un checkpoint válido.")

    p_best = best_model.predict_proba(
        prepared["X_val"]
    )[:, 1]

    info = {
        **metricas_binarias(prepared["y_val"], p_best),
        "seed": int(seed),
        "best_epoch": int(best_epoch),
        "trained_epochs": int(epoch),
        "stop_reason": stop_reason,
        "parameters": contar_parametros(best_model),
        "seconds": time.perf_counter() - start
    }

    return best_model, info, pd.DataFrame(history), p_best


# 23.2. Generar configuraciones candidatas
def candidate_configs(config):

    rng = np.random.RandomState(config["seed_busqueda"])
    candidates = []

    solvers = list(dict.fromkeys(
        s for s, _ in config["optimizadores_y_lr"]
    ))

    for solver in solvers:

        rates = [
            lr for s, lr in config["optimizadores_y_lr"]
            if s == solver
        ]

        for activation in config["activaciones"]:

            pool = [
                {
                    "hidden_layer_sizes": list(arch),
                    "activation": activation,
                    "solver": solver,
                    "alpha": float(alpha),
                    "learning_rate_init": float(lr)
                }
                for arch, alpha, lr in product(
                    config["arquitecturas"],
                    config["alphas"],
                    rates
                )
            ]

            count = min(
                config["configuraciones_por_optimizador_y_activacion"],
                len(pool)
            )

            indices = rng.choice(
                len(pool),
                size=count,
                replace=False
            )

            candidates.extend(
                pool[int(i)] for i in indices
            )

    return candidates


