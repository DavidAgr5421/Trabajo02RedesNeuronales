# 15. Contrastar descriptivamente las hipótesis

import numpy as np

def tabla_por_grupos(variable, bins, etiquetas):
    grupos = pd.cut(
        train[variable],
        bins=bins,
        labels=etiquetas,
        right=False,
        include_lowest=True
    ).astype("string").fillna("Sin dato")

    resultado = pd.DataFrame({
        "grupo": grupos,
        "y": train["target_pd"]
    }).groupby("grupo").agg(
        creditos=("y", "size"),
        clase_1=("y", "sum")
    )

    orden = etiquetas + (["Sin dato"] if "Sin dato" in resultado.index else [])
    resultado = resultado.reindex(orden)

    resultado[["creditos", "clase_1"]] = (
        resultado[["creditos", "clase_1"]]
        .fillna(0)
        .astype(int)
    )

    resultado["tasa_clase_1"] = resultado["clase_1"] / resultado["creditos"]
    resultado["variable"] = variable

    return resultado.reset_index()

ESPECIFICACIONES = {
    "H1": ("dti", [0, 10, 20, 30, np.inf], ["0 a <10", "10 a <20", "20 a <30", "30 o más"]),
    "H2": ("revol_util", [0, 30, 60, 90, np.inf], ["0 a <30", "30 a <60", "60 a <90", "90 o más"]),
    "H3": ("delinq_2yrs", [0, 1, 2, np.inf], ["0", "1", "2 o más"]),
    "H4": ("credit_history_years", [0, 10, 20, np.inf], ["0 a <10", "10 a <20", "20 o más"]),
}

tablas_hipotesis = {}

for hipotesis, (variable, bins, etiquetas) in ESPECIFICACIONES.items():
    tabla = tabla_por_grupos(variable, bins, etiquetas)
    tabla["hipotesis"] = hipotesis

    assert int(tabla["creditos"].sum()) == len(train)

