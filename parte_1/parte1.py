"""## 25 Perceptrón multicapa y activaciones

Una neurona calcula una suma ponderada más un sesgo y aplica una función de activación: $a=\phi(w^Tx+b)$. En el MLP se encadenan capas:

$$h^{(0)}=x,\quad z^{(l)}=W^{(l)}h^{(l-1)}+b^{(l)},\quad h^{(l)}=\phi(z^{(l)}).$$

Las capas ocultas de la búsqueda usan ReLU, $\phi(z)=\max(0,z)$, o tanh, $\phi(z)=\tanh(z)$. Sus derivadas son $1$ para ReLU cuando $z>0$ y $0$ cuando $z<0$ (se adopta $0$ en el punto no diferenciable), y $1-\tanh^2(z)$ para tanh.

En clasificación binaria, la salida de `MLPClassifier` utiliza una sigmoide para producir $p\in(0,1)$. Su derivada es $\sigma(z)(1-\sigma(z))$. Se usa la misma BCE derivada de Bernoulli; la red introduce transformaciones no lineales entre entrada y salida.

**Retropropagación.** Con sigmoide y BCE, el error de salida por muestra es $\delta^{(L)}=p-y$. Para una capa oculta,

$$\delta^{(l)}=\left((W^{(l+1)})^T\delta^{(l+1)}\right)\odot\phi'(z^{(l)}).$$

En un minibatch de tamaño $m$, el gradiente de cada matriz es el promedio de los productos entre errores y activaciones previas. L2 añade un término proporcional a $W^{(l)}$; los sesgos reciben el promedio de los errores. La implementación usa `alpha` y divide la contribución L2 entre el número de muestras del lote durante su actualización; por eso su valor numérico no equivale directamente a C ni a un lambda con otra convención de escala.

Se aplican dos formas de regularización: penalización L2 sobre los pesos, con término de forma $\frac{\lambda}{2}\sum_l\|W^{(l)}\|_F^2$, y parada temprana sobre validation. Los valores exactos de `alpha`, tamaño del lote y checkpoint se guardan para reproducir la convención utilizada.

**Optimizadores comparados.** SGD utiliza momento $\mu=0.9$, sin Nesterov:

$$v_t=\mu v_{t-1}-\eta g_t,\qquad\theta_t=\theta_{t-1}+v_t.$$

Adam mantiene momentos $m_t=\beta_1m_{t-1}+(1-\beta_1)g_t$ y $v_t=\beta_2v_{t-1}+(1-\beta_2)g_t^2$. La forma operativa de scikit-learn 1.8 corrige el paso mediante

$$\eta_t=\eta\frac{\sqrt{1-\beta_2^t}}{1-\beta_1^t},\qquad
\theta_t=\theta_{t-1}-\eta_t\frac{m_t}{\sqrt{v_t}+\epsilon}.$$

Se fijan $\beta_1=0.9$, $\beta_2=0.999$ y $\epsilon=10^{-8}$. El parámetro t cuenta actualizaciones por minibatch. Esta expresión especifica dónde se ubica epsilon; no se intercambia sin explicación con otras convenciones de corrección de sesgo. El algoritmo Adam se fundamenta en Kingma y Ba (2015), y la forma operativa se comprobó en el código del optimizador incluido en scikit-learn 1.8.

La Tabla 2 presenta las arquitecturas e hiperparámetros evaluados y sus resultados.
"""

